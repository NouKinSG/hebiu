#!/bin/bash
# 自己写数据来源的模板：复制一份到 ~/.hebiu/sources/<名字>.sh，改好后 chmod +x，
# 再在设置页「来源」里打开（或在 ~/.hebiu/hebiu.md 的 ## sources 下加一行「- 名字: 15」）。
#
# 规则：往标准输出打印一个 JSON 数组，每条一个待办：
#   id     必填，来源里的唯一标识。下次同步还是同一个 id，就认为是同一条
#   title  必填
#   due    可选，「2026-10-26 10:00」「2026-10-26」或 ISO 8601
#   note   可选，备注
#   link   可选，在待办里点了能打开
# 上次有、这次没有的（还没打勾的）会自动从待办里删掉；退出码不是 0 算失败，失败时待办保持不变。
#
# 下面这个例子：每周一给一条「交周报」，周一 17:00 提醒
set -euo pipefail
if [ "$(date +%u)" = "1" ]; then
  echo "[{\"id\": \"weekly-$(date +%Y-%W)\", \"title\": \"交周报\", \"due\": \"$(date +%Y-%m-%d) 17:00\"}]"
else
  echo "[]"
fi
